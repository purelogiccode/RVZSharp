#Requires -Version 7.0
<#
.SYNOPSIS
    Generates the WinGet manifests for the Windows RVZSharp CLI release bundles.

.DESCRIPTION
    Reads the win-x64 and win-arm64 release zips, computes their SHA-256 hashes and writes
    a complete set of WinGet manifests (version, installer and en-US locale). The generated
    directory can be submitted with `wingetcreate submit --path <directory>` or attached to
    the GitHub release for manual submission.

.PARAMETER Version
    The release version without the leading `v` (for example 1.2.0).

.PARAMETER ReleaseTag
    The GitHub release tag (for example v1.2.0).

.PARAMETER InputDirectory
    Directory containing rvzsharp_v<Version>_win-x64.zip and the win-arm64 zip.

.PARAMETER OutputDirectory
    Directory where the three manifest YAML files are written.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string] $Version,

    [Parameter(Mandatory = $true)]
    [string] $ReleaseTag,

    [Parameter(Mandatory = $true)]
    [string] $InputDirectory,

    [Parameter(Mandatory = $true)]
    [string] $OutputDirectory
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$packageIdentifier = 'PureLogicCode.RVZSharp'
$manifestVersion = '1.10.0'
$repository = 'purelogiccode/RVZSharp'
$releaseUrl = "https://github.com/$repository/releases/download/$ReleaseTag"

$installers = @(
    [pscustomobject]@{ Rid = 'win-x64'; Architecture = 'x64' },
    [pscustomobject]@{ Rid = 'win-arm64'; Architecture = 'arm64' }
)

$installerBlocks = foreach ($installer in $installers) {
    $zipName = "rvzsharp_v${Version}_$($installer.Rid).zip"
    $zipPath = Join-Path $InputDirectory $zipName
    if (-not (Test-Path -LiteralPath $zipPath -PathType Leaf)) {
        throw "Missing WinGet installer: $zipPath"
    }

    $hash = (Get-FileHash -LiteralPath $zipPath -Algorithm SHA256).Hash.ToLowerInvariant()
    @"
- Architecture: $($installer.Architecture)
  InstallerUrl: $releaseUrl/$zipName
  InstallerSha256: $hash
"@
}

New-Item -ItemType Directory -Path $OutputDirectory -Force | Out-Null

$versionManifest = @"
# yaml-language-server: `$schema=https://aka.ms/winget-manifest.version.$manifestVersion.schema.json
# Generated by scripts/Generate-WingetManifests.ps1. Do not edit.
PackageIdentifier: $packageIdentifier
PackageVersion: $Version
DefaultLocale: en-US
ManifestType: version
ManifestVersion: $manifestVersion
"@

$installerManifest = @"
# yaml-language-server: `$schema=https://aka.ms/winget-manifest.installer.$manifestVersion.schema.json
# Generated by scripts/Generate-WingetManifests.ps1. Do not edit.
PackageIdentifier: $packageIdentifier
PackageVersion: $Version
InstallerType: zip
NestedInstallerType: portable
NestedInstallerFiles:
- RelativeFilePath: RVZSharp.exe
  PortableCommandAlias: rvzsharp
Installers:
$($installerBlocks -join "`n")
Dependencies:
  PackageDependencies:
  - PackageIdentifier: Microsoft.DotNet.Runtime.11
    MinimumVersion: 11.0.0
ManifestType: installer
ManifestVersion: $manifestVersion
"@

$localeManifest = @"
# yaml-language-server: `$schema=https://aka.ms/winget-manifest.defaultLocale.$manifestVersion.schema.json
# Generated by scripts/Generate-WingetManifests.ps1. Do not edit.
PackageIdentifier: $packageIdentifier
PackageVersion: $Version
PackageLocale: en-US
Publisher: Pure Logic Code
PublisherUrl: https://github.com/$repository
PublisherSupportUrl: https://github.com/$repository/issues
PackageName: RVZSharp
PackageUrl: https://github.com/$repository
License: GPL-2.0-or-later
LicenseUrl: https://raw.githubusercontent.com/$repository/master/LICENSE
Copyright: Copyright (c) Peterson Fernandes
ShortDescription: Convert, inspect, verify and extract GameCube/Wii disc images.
Description: >-
  Pure managed command-line tool for Dolphin RVZ/WIA, GCZ, CISO/WBI, WBFS, TGC, NFS and
  ISO disc images. Converts, inspects, verifies and extracts GameCube and Wii discs.
Moniker: rvzsharp
Tags:
- gamecube
- wii
- rvz
- wia
- gcz
- ciso
- wbfs
- iso
- disc-image
- dolphin
- cli
ReleaseNotesUrl: https://github.com/$repository/releases/tag/$ReleaseTag
ManifestType: defaultLocale
ManifestVersion: $manifestVersion
"@

$utf8 = [System.Text.UTF8Encoding]::new($false)
$files = [ordered]@{
    "$packageIdentifier.yaml" = $versionManifest
    "$packageIdentifier.installer.yaml" = $installerManifest
    "$packageIdentifier.locale.en-US.yaml" = $localeManifest
}

foreach ($entry in $files.GetEnumerator()) {
    $path = Join-Path $OutputDirectory $entry.Key
    [System.IO.File]::WriteAllText($path, $entry.Value + "`n", $utf8)
    Write-Output "Wrote $path"
}
